class TestCallSites:
    """The one way this commit could break the byte-exact golden.

    Every added line in ``src/aicds/models/`` must sit strictly AFTER the block
    that owns ``PerformanceIndex.txt`` has closed -- the same discipline as
    ``RankAccumulator.write``, and for the same reason: an exception raised
    before the timing trailer is written would surface as
    ``test_golden.strip_trailer``'s "No timing trailer found", i.e. a GOLDEN
    FAILURE THAT LOOKS LIKE THE PIPELINE CHANGED.

    Asserted on the source text because the alternative is a full 10-fold run.
    """

    @pytest.mark.parametrize(
        "module,close_marker",
        [
            ("baseline_sent2vec.py", "performance_out_file.write(line + \"\\n\")"),
            ("bert_models.py", "performance_out_file.close()"),
        ],
    )
    def test_metadata_is_written_after_the_performance_index_closes(
        self, module, close_marker
    ):
        path = os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "src",
            "aicds",
            "models",
            module,
        )
        with open(path, encoding="utf-8") as handle:
            text = handle.read()

        call = text.index("runs.write_run_metadata(")
        assert text.rindex(close_marker) < call, module
        # And after the rank metrics, so the file's presence means the run
        # reached the very end.
        assert text.rindex("rank_accumulator.write(") < call, module
        # Nothing may touch the performance handle afterwards.
        assert "performance_out_file" not in text[call:], module
