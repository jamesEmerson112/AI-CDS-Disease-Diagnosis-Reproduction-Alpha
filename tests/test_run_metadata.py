"""``run_metadata.json``: what produced a run, and what reads it back (P14).

Until this landed, attribution rested entirely on the results-directory name --
``scripts/compare_models.py`` carried a comment saying exactly that. The cost was
not theoretical: the P29 attribution experiment has to harvest into a
config-named root after *each* batch, because both batches emit identically-named
``Prediction_Output_<Model>_<stamp>`` directories into one working directory, and
sorting them afterwards would mean inferring the config from timestamp order
alone -- in the one experiment whose entire purpose is attribution.

Three properties are load-bearing here and each has its own section below.

**The record is self-sufficient.** ``pipeline`` carries the registry *name* and
all three fields. A name with no reader was the P4 lesson; a name with no fields
is its sibling. If the registry is ever edited, the fields still say what ran.

**The fold split is identified by content, not by name.**
``data/folds_grouped/`` is gitignored and regenerated by
``scripts/make_folds.py``, so the git SHA cannot cover it -- git never saw those
files. ``fold_dir: folds_grouped`` alone therefore does not identify a split, and
without the hash a corrected or DRG run is not reproducible from its own record.

**Writing it can never cost a run.** A 13-minute baseline run or a 35-minute
three-model run whose numbers are already on disk must not be lost to a git
lookup. Every failure path is asserted to warn and return rather than raise.

The synthetic fold directories are built under a tmp *repo root* rather than
pointed at ``data/``: ``folds_grouped/`` is regenerated output that may legally
be absent, so a test reading it would pass or fail on whether somebody had run
``make_folds.py`` -- which is not what any of these tests are about.
"""

