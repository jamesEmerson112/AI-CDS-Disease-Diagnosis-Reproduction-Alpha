class TestPayload:
    def test_legacy_run_records_every_field(self, run_dir, repo):
        payload, path = _write_and_read(
            run_dir, LEGACY, "BioSentVec", "05082026_18-55-32", repo
        )

        assert os.path.basename(path) == "run_metadata.json"
        assert payload["metadata_version"] == 1
        assert payload["stamp"] == "05082026_18-55-32"
        assert payload["k_fold"] == K_FOLD

        assert payload["pipeline"] == {
            "name": "legacy",
            "fold_dir": "folds",
            "preprocess_version": "legacy",
            "grader": "cosine",
        }
        assert payload["model"] == {"key": "baseline", "label": "BioSentVec"}

        # The hash exists and is a hex sha256; its *stability* is tested below.
        assert isinstance(payload["fold_dir_sha256"], str)
        assert len(payload["fold_dir_sha256"]) == 64
        # The split hashed, so nothing is missing. (``git_unavailable`` is
        # expected here and only here: the fixture repo root is a tmp directory
        # with no working tree, which is precisely the "don't know" branch.)
        assert "fold_dir_missing" not in payload["notes"]

        assert set(payload["git"]) == {"sha", "dirty"}
        assert set(payload["environment"]) == {"platform", "python", "numpy"}
        assert payload["environment"]["python"].count(".") >= 1

    def test_git_state_is_captured_against_a_real_working_tree(self, run_dir):
        """The fixture root has no ``.git``; this repository does.

        Run against ``REPO_ROOT`` -- which is how both arms call it, and NEVER
        ``os.getcwd()``: the golden chdirs into a tmp directory, so a cwd-based
        lookup would record the wrong repository or nothing at all.
        """
        payload, _ = _write_and_read(
            run_dir, LEGACY, "BioSentVec", "05082026_18-55-32", runs.REPO_ROOT
        )
        if payload["git"]["sha"] is None:  # no git on this machine
            pytest.skip("git unavailable")
        assert len(payload["git"]["sha"]) == 40
        assert set(payload["git"]["sha"]) <= set("0123456789abcdef")
        assert isinstance(payload["git"]["dirty"], bool)
        assert payload["notes"] == []

    def test_drg_run_records_the_grader_that_actually_ran(self, run_dir, repo):
        payload, _ = _write_and_read(
            run_dir, GRADER_DRG, "Bio_ClinicalBERT", "06082026_15-31-02", repo
        )
        assert payload["pipeline"] == {
            "name": "drg",
            "fold_dir": "folds_grouped",
            "preprocess_version": "corrected",
            "grader": "drg-exact",
        }
        assert payload["model"] == {
            "key": "bio_clinical_bert",
            "label": "Bio_ClinicalBERT",
        }

    def test_the_recorded_name_round_trips_through_the_registry(self, run_dir, repo):
        """``from_name(payload['pipeline']['name'])`` must rebuild the same config.

        This is the property that lets a reader trust the name instead of the
        three fields, and it is what ``compare_models.recorded_pipeline`` relies
        on.
        """
        payload, _ = _write_and_read(run_dir, GRADER_DRG, "BlueBERT", "0" * 8 + "_00-00-00", repo)
        assert from_name(payload["pipeline"]["name"]) == GRADER_DRG

    def test_json_is_sorted_indented_and_newline_terminated(self, run_dir, repo):
        path = runs.write_run_metadata(
            run_dir, LEGACY, "BiomedBERT", "05082026_19-38-16", repo_root=repo
        )
        with open(path, encoding="utf-8", newline="") as handle:
            text = handle.read()
        assert text.endswith("\n")
        # newline="\n" at write time, so the bytes match on Windows and Linux --
        # this file is a provenance record that gets compared across the two.
        assert "\r\n" not in text
        assert "\n  " in text, "expected indent=2"
        keys = [line.split('"')[1] for line in text.splitlines() if line.startswith("  \"")]
        assert keys == sorted(keys), keys

    def test_an_unregistered_model_name_warns_rather_than_writing_a_guess(
        self, run_dir, repo, capsys
    ):
        """``model_key`` refuses invented keys; the never-raises policy takes it from there."""
        assert runs.write_run_metadata(run_dir, LEGACY, "GPT-9", "0" * 8 + "_00-00-00", repo_root=repo) is None
        assert "[WARN] run_metadata.json not written" in capsys.readouterr().out
        assert not os.path.exists(os.path.join(run_dir, "run_metadata.json"))


