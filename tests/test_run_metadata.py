class TestNeverRaises:
    def test_git_exploding_still_writes_the_run_record(
        self, run_dir, repo, monkeypatch, capsys
    ):
        """The numbers are already on disk. A git lookup may not take them down."""

        def explode(*args, **kwargs):
            raise RuntimeError("git went to lunch")

        monkeypatch.setattr(subprocess, "run", explode)

        payload, _ = _write_and_read(
            run_dir, LEGACY, "BioSentVec", "05082026_18-55-32", repo
        )
        assert payload["git"] == {"sha": None, "dirty": None}
        assert "git_unavailable" in payload["notes"]
        # And everything git had nothing to do with survived.
        assert payload["pipeline"]["name"] == "legacy"
        assert payload["fold_dir_sha256"] is not None

    def test_dirty_is_null_not_false_when_git_cannot_be_asked(
        self, run_dir, repo, monkeypatch
    ):
        """"clean" and "don't know" are different claims.

        The same distinction ``_git_ignores`` draws with its ``answered`` flag. A
        provenance record that asserts the first when it means the second is
        worse than one that admits the gap.
        """
        monkeypatch.setattr(
            subprocess, "run", lambda *a, **k: (_ for _ in ()).throw(OSError("no git"))
        )
        payload, _ = _write_and_read(run_dir, LEGACY, "BiomedBERT", "0" * 8 + "_00-00-00", repo)
        assert payload["git"]["dirty"] is None

    def test_unwritable_destination_warns_and_returns_none(self, repo, tmp_path, capsys):
        missing = str(tmp_path / "no" / "such" / "directory")
        assert runs.write_run_metadata(missing, LEGACY, "BlueBERT", "0" * 8 + "_00-00-00", repo_root=repo) is None
        assert "[WARN] run_metadata.json not written" in capsys.readouterr().out

    def test_a_fold_file_vanishing_mid_hash_warns_rather_than_raising(
        self, run_dir, repo, monkeypatch, capsys
    ):
        real_walk = os.walk

        def walk_then_delete(top, *args, **kwargs):
            result = list(real_walk(top, *args, **kwargs))
            for directory, _subdirs, files in result:
                for name in files:
                    os.remove(os.path.join(directory, name))
            return result

        monkeypatch.setattr(os, "walk", walk_then_delete)
        assert runs.write_run_metadata(run_dir, LEGACY, "BlueBERT", "0" * 8 + "_00-00-00", repo_root=repo) is None
        assert "[WARN] run_metadata.json not written" in capsys.readouterr().out


