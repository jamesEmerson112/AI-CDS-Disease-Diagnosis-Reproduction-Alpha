def _make_run(root, key, stamp, pipeline_name=None):
    """A discoverable nested run, optionally carrying provenance."""
    path = os.path.join(root, key, stamp)
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, "PerformanceIndex.txt"), "w", encoding="utf-8") as f:
        f.write("marker\n")
    if pipeline_name is not None:
        payload = {
            "metadata_version": 1,
            "pipeline": {
                "name": pipeline_name,
                "fold_dir": "folds",
                "preprocess_version": "legacy",
                "grader": "cosine",
            },
        }
        with open(os.path.join(path, "run_metadata.json"), "w", encoding="utf-8") as f:
            json.dump(payload, f)
    return path


class TestResolvePipeline:
    def test_metadata_beats_a_wrong_directory_name(self, tmp_path, capsys):
        """The whole point of P14: the tree says what it is, the folder only hints.

        The root is named ``results`` -- which ``_PIPELINE_BY_DIRNAME`` maps to
        ``legacy`` -- while the runs inside record ``drg``. Before this commit
        the folder name won and 16 sanity checks were run against the wrong
        pipeline's expectations.
        """
        root = str(tmp_path / "results")
        _make_run(root, "baseline", "06082026_15-18-52", "drg")
        _make_run(root, "biomedbert", "06082026_15-42-04", "drg")

        assert compare_models.resolve_pipeline(root, None) == "drg"
        out = capsys.readouterr().out
        assert "pipeline from run_metadata.json: drg" in out
        assert "inferring pipeline from directory name" not in out

    def test_a_metadata_less_tree_falls_back_and_says_so(self, tmp_path, capsys):
        root = str(tmp_path / "results_drg")
        _make_run(root, "baseline", "06082026_15-18-52")

        assert compare_models.resolve_pipeline(root, None) == "drg"
        out = capsys.readouterr().out
        assert "[WARN] no run_metadata.json under" in out
        assert "pre-C8 runs" in out
        assert "pipeline inferred from directory name: drg" in out

    def test_the_fallback_warning_prints_once_per_invocation(self, tmp_path, capsys):
        root = str(tmp_path / "results")
        for key in ("baseline", "biomedbert", "bluebert"):
            _make_run(root, key, "05082026_18-55-32")
        compare_models.resolve_pipeline(root, None)
        assert capsys.readouterr().out.count("[WARN] no run_metadata.json") == 1

    def test_the_warning_prints_even_when_pipeline_is_explicit(self, tmp_path, capsys):
        """The absence of provenance is a fact about the tree, not about the flag."""
        root = str(tmp_path / "results_p5")
        _make_run(root, "baseline", "06082026_15-18-52")
        assert compare_models.resolve_pipeline(root, "drg") == "drg"
        out = capsys.readouterr().out
        assert "[WARN] no run_metadata.json under" in out
        assert "pipeline: drg (explicit)" in out

    def test_a_mixed_tree_is_a_hard_error_naming_both_runs(self, tmp_path):
        root = str(tmp_path / "results")
        legacy_run = _make_run(root, "baseline", "05082026_18-55-32", "legacy")
        drg_run = _make_run(root, "biomedbert", "06082026_15-42-04", "drg")

        with pytest.raises(SystemExit) as excinfo:
            compare_models.resolve_pipeline(root, None)
        message = str(excinfo.value)
        assert "mixed-pipeline" in message
        # Both runs named: the reader's next action is to look at them.
        assert legacy_run in message and drg_run in message
        assert "'legacy'" in message and "'drg'" in message

    def test_a_mixed_tree_is_caught_across_two_runs_of_one_arm(self, tmp_path):
        """Every run is inspected, not just the latest per arm.

        The report draws one run per arm, so a stale run from another pipeline
        would otherwise sit in the same root, uninspected and invisible.
        """
        root = str(tmp_path / "results")
        _make_run(root, "baseline", "05082026_18-55-32", "legacy")
        _make_run(root, "baseline", "06082026_15-18-52", "drg")
        with pytest.raises(SystemExit, match="mixed-pipeline"):
            compare_models.resolve_pipeline(root, None)

    def test_partial_migration_in_time_is_not_a_mixed_tree(self, tmp_path, capsys):
        """Old runs beside one fresh run is normal; only mixed PIPELINES are not."""
        root = str(tmp_path / "results_corrected")
        _make_run(root, "baseline", "05082026_18-55-32")  # pre-C8, no metadata
        _make_run(root, "biomedbert", "06082026_15-42-04", "corrected")

        assert compare_models.resolve_pipeline(root, None) == "corrected"
        assert "[WARN] no run_metadata.json" not in capsys.readouterr().out

    def test_malformed_metadata_is_treated_as_absent(self, tmp_path, capsys):
        """A provenance file must not be able to kill a report the numbers support."""
        root = str(tmp_path / "results")
        path = _make_run(root, "baseline", "05082026_18-55-32")
        with open(os.path.join(path, "run_metadata.json"), "w", encoding="utf-8") as f:
            f.write("{not json at all")

        assert compare_models.resolve_pipeline(root, None) == "legacy"
        assert "[WARN] no run_metadata.json" in capsys.readouterr().out

    def test_a_null_pipeline_name_is_treated_as_absent(self, tmp_path, capsys):
        """A hand-built config records ``name: null``; there is nothing to read."""
        root = str(tmp_path / "results")
        _make_run(root, "baseline", "05082026_18-55-32", None)
        path = os.path.join(root, "baseline", "05082026_18-55-32")
        with open(os.path.join(path, "run_metadata.json"), "w", encoding="utf-8") as f:
            json.dump({"metadata_version": 1, "pipeline": {"name": None}}, f)

        assert compare_models.resolve_pipeline(root, None) == "legacy"
        assert "[WARN] no run_metadata.json" in capsys.readouterr().out

    def test_explicit_flag_still_wins_over_metadata_but_says_they_disagree(
        self, tmp_path, capsys
    ):
        root = str(tmp_path / "results")
        _make_run(root, "baseline", "05082026_18-55-32", "drg")
        assert compare_models.resolve_pipeline(root, "legacy") == "legacy"
        out = capsys.readouterr().out
        assert "records pipeline 'drg'" in out
        assert "using the explicit flag" in out

    def test_an_unknown_dirname_with_no_metadata_still_refuses(self, tmp_path, capsys):
        """The pre-existing hard refusal is untouched for metadata-less trees."""
        root = str(tmp_path / "some_scratch_dir")
        _make_run(root, "baseline", "05082026_18-55-32")
        with pytest.raises(SystemExit, match="cannot tell which pipeline"):
            compare_models.resolve_pipeline(root, None)


