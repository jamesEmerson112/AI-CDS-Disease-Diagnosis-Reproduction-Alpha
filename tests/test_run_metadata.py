class TestFoldDigest:
    def test_stable_across_calls(self, repo):
        first = runs.fold_dir_digest("folds", repo_root=repo)
        second = runs.fold_dir_digest("folds", repo_root=repo)
        assert first == second
        assert first is not None

    def test_differs_between_fold_dirs(self, repo):
        assert runs.fold_dir_digest("folds", repo_root=repo) != runs.fold_dir_digest(
            "folds_grouped", repo_root=repo
        )

    def test_changes_when_a_fold_file_changes(self, repo):
        before = runs.fold_dir_digest("folds", repo_root=repo)
        target = os.path.join(repo, "data", "folds", "Fold1", "TestSet.txt")
        with open(target, "a", encoding="utf-8") as handle:
            handle.write("one more admission\n")
        assert runs.fold_dir_digest("folds", repo_root=repo) != before

    def test_changes_when_a_case_moves_between_folds(self, repo):
        """Which admission sits in which fold IS the split.

        A content-only hash would call these two experiments identical, because
        swapping two fold files leaves the multiset of bytes untouched. Hashing
        the relative path alongside the content is what prevents that.
        """
        before = runs.fold_dir_digest("folds", repo_root=repo)
        first = os.path.join(repo, "data", "folds", "Fold0", "TestSet.txt")
        second = os.path.join(repo, "data", "folds", "Fold1", "TestSet.txt")
        with open(first, encoding="utf-8") as handle:
            first_text = handle.read()
        with open(second, encoding="utf-8") as handle:
            second_text = handle.read()
        with open(first, "w", encoding="utf-8") as handle:
            handle.write(second_text)
        with open(second, "w", encoding="utf-8") as handle:
            handle.write(first_text)
        assert runs.fold_dir_digest("folds", repo_root=repo) != before

    def test_missing_fold_dir_is_null_and_noted(self, run_dir, repo):
        """Ordinary, not an error: folds_grouped/ is gitignored, regenerated output."""
        config = PipelineConfig(fold_dir="folds_that_were_never_generated")
        payload, _ = _write_and_read(
            run_dir, config, "BlueBERT", "05082026_19-52-30", repo
        )
        assert payload["fold_dir_sha256"] is None
        assert "fold_dir_missing" in payload["notes"]
        # The record is still complete about everything else.
        assert payload["pipeline"]["fold_dir"] == "folds_that_were_never_generated"


