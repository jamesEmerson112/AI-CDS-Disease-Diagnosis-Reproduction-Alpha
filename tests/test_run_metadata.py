class TestNameOf:
    def test_every_selectable_pipeline_round_trips(self):
        """The registry-completeness guard, extended to the reverse direction.

        ``test_drg_grader.test_every_selectable_pipeline_has_a_live_grader``
        makes the same shape of claim about graders: no config may be
        selectable-but-unhonoured. Here: no config may be selectable but
        unnameable, because a run driven by ``--pipeline X`` that records
        ``name: null`` would push every reader back onto the three fields and
        quietly undo half of P14.
        """
        for name in PIPELINE_NAMES:
            assert name_of(from_name(name)) == name

    def test_value_equality_not_identity(self):
        """A rebuilt config gets its name back. Frozen dataclass equality is the point."""
        rebuilt = PipelineConfig(
            fold_dir="folds_grouped",
            preprocess_version="corrected",
            grader="drg-exact",
        )
        assert rebuilt is not GRADER_DRG
        assert name_of(rebuilt) == "drg"

    def test_a_hand_built_config_is_none_not_an_error(self):
        """None is a first-class answer -- the three fields still identify the run."""
        hand_built = PipelineConfig(fold_dir="folds_grouped", grader="drg-exact")
        assert name_of(hand_built) is None

    def test_null_name_still_leaves_a_fully_described_pipeline(self, run_dir, repo):
        hand_built = PipelineConfig(fold_dir="folds_grouped", grader="drg-exact")
        payload, _ = _write_and_read(
            run_dir, hand_built, "BlueBERT", "0" * 8 + "_00-00-00", repo
        )
        assert payload["pipeline"] == {
            "name": None,
            "fold_dir": "folds_grouped",
            "preprocess_version": "legacy",
            "grader": "drg-exact",
        }


