def _write_fold_dir(repo_root, fold_dir, payload):
    """A minimal ``<repo_root>/data/<fold_dir>/Fold{0,1}/`` split."""
    for fold in (0, 1):
        directory = os.path.join(repo_root, "data", fold_dir, "Fold%d" % fold)
        os.makedirs(directory, exist_ok=True)
        for name in ("TrainingSet.txt", "TestSet.txt"):
            with open(os.path.join(directory, name), "w", encoding="utf-8") as handle:
                handle.write("%s/%s/%d\n" % (payload, name, fold))
    return os.path.join(repo_root, "data", fold_dir)


@pytest.fixture
def repo(tmp_path):
    """A tmp repo root carrying ``folds`` and ``folds_grouped`` with distinct content."""
    root = str(tmp_path / "repo")
    _write_fold_dir(root, "folds", "legacy-split")
    _write_fold_dir(root, "folds_grouped", "grouped-split")
    return root


@pytest.fixture
def run_dir(tmp_path):
    path = str(tmp_path / "run")
    os.makedirs(path)
    return path


def _write_and_read(run_dir, config, model_name, stamp, repo_root):
    path = runs.write_run_metadata(
        run_dir, config, model_name, stamp, repo_root=repo_root
    )
    assert path is not None, "write_run_metadata returned None on a healthy path"
    with open(path, encoding="utf-8") as handle:
        return json.load(handle), path


